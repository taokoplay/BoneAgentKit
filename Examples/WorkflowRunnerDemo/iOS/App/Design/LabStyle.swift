import SwiftUI

/// One accent and a small spacing/corner scale across the native demo.
enum LabStyle {
    static let accent = Color("AccentColor")
    static let onAccent = Color("LabOnAccent")
    static let canvas = Color("LabCanvas")
    static let surface = Color("LabSurface")
    static let inset = Color("LabInset")
    static let pageInset: CGFloat = 20
    static let sectionSpacing: CGFloat = 24
    static let itemSpacing: CGFloat = 12
    static let cardRadius: CGFloat = 20
    static let controlRadius: CGFloat = 12
}
